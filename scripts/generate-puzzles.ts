/**
 * Finds Toguz Korgool puzzles in self-played games and writes src/learn/toguzPuzzles.ts.
 * Every puzzle has exactly one right answer, checked with the game engine.
 *
 *   npx vite-node scripts/generate-puzzles.ts
 */
import { writeFileSync } from 'node:fs';
import { applyMove, createInitialState, legalMoves, type GameState } from '../src/game/engine';
import { classifyPuzzle, type PuzzleKind } from '../src/learn/puzzleCheck';

const WANT: Record<PuzzleKind, number> = { capture: 8, tuzduk: 6, foresight: 8 };
const found: Record<PuzzleKind, { state: GameState; solution: number }[]> = { capture: [], tuzduk: [], foresight: [] };

let seed = 20261112;
const random = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);

/** A plausible human-like move: usually the best immediate gain, sometimes anything. */
function playoutMove(state: GameState): number {
  const moves = legalMoves(state, state.current);
  if (random() < 0.35) return moves[Math.floor(random() * moves.length)];
  let best = moves[0];
  let bestGain = -1;
  for (const move of moves) {
    const { result } = applyMove(state, move);
    const gain = result.gained[state.current] + random();
    if (gain > bestGain) {
      bestGain = gain;
      best = move;
    }
  }
  return best;
}

const seen = new Set<string>();
for (let game = 0; game < 4000; game++) {
  if (Object.entries(WANT).every(([kind, n]) => found[kind as PuzzleKind].length >= n)) break;
  let state = createInitialState();
  let tookOne = false; // at most one puzzle per game keeps them varied
  while (!state.gameOver) {
    if (!tookOne && state.current === 1 && state.moveCount >= 8 && state.moveCount <= 90 && random() < 0.3) {
      const key = state.pits.join(',') + state.tuzduk.join(',');
      const puzzle = classifyPuzzle(state);
      if (puzzle && found[puzzle.kind].length < WANT[puzzle.kind] && !seen.has(key)) {
        seen.add(key);
        found[puzzle.kind].push({ state, solution: puzzle.solution });
        tookOne = true;
      }
    }
    state = applyMove(state, playoutMove(state)).nextState;
  }
}

const lines: string[] = [];
for (const kind of ['capture', 'tuzduk', 'foresight'] as PuzzleKind[]) {
  found[kind].forEach(({ state, solution }, i) => {
    lines.push(
      `  { id: '${kind}-${i + 1}', kind: '${kind}', solution: ${solution}, ` +
        `pits: [${state.pits.join(', ')}], kazan: [${state.kazan.join(', ')}], ` +
        `tuzduk: [${state.tuzduk.join(', ')}], moveCount: ${state.moveCount} },`,
    );
  });
}

writeFileSync(
  new URL('../src/learn/toguzPuzzles.ts', import.meta.url),
  `/** Generated by scripts/generate-puzzles.ts — every entry is re-checked in toguzPuzzles.test.ts. */
import type { PuzzleData } from './puzzleCheck';

export const TOGUZ_PUZZLES: PuzzleData[] = [
${lines.join('\n')}
];
`,
);
